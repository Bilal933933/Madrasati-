/** يحوّل الدرس إلى مستند فقرة (TipTap-like) بعقدة مشهد في وسطه */
export function lessonDoc(lesson: SandboxSceneLesson): SandboxDoc {
  return {
    type: "doc",
    content: [
      {
        type: "paragraph",
        content: [{ type: "text", text: lesson.intro }],
      },
      {
        type: "interactive_lab",
        attrs: {
          labKind: "scene",
          sceneId: lesson.sceneId,
          caption: lesson.caption,
        },
      },
      ...lesson.notes.map((note) => ({
        type: "paragraph" as const,
        content: [{ type: "text" as const, text: note }],
      })),
      {
        type: "blockquote",
        content: [
          {
            type: "paragraph",
            content: [{ type: "text", text: lesson.takeaway }],
          },
        ],
      },
    ],
  };
}

export function getSceneLesson(id: string): SandboxSceneLesson | null {
  return SCENE_LESSONS.find((lesson) => lesson.id === id) ?? null;
}
