    /**
     * سؤال اختيار من متعدد — مفتاح مطابق بيئة ExamBankService (options + correct داخل content).
     */
    private static function easyMcq(string $q, array $options, int $answer, string $explanation = ''): array
    {
        return self::mcq('easy', $q, $options, $answer, $explanation);
    }

    private static function mediumMcq(string $q, array $options, int $answer, string $explanation = ''): array
    {
        return self::mcq('medium', $q, $options, $answer, $explanation);
    }

    private static function hardMcq(string $q, array $options, int $answer, string $explanation = ''): array
    {
        return self::mcq('hard', $q, $options, $answer, $explanation);
    }

    private static function mcq(string $difficulty, string $q, array $options, int $answer, string $explanation): array
    {
        $mapped = [];
        foreach ($options as $index => $content) {
            $mapped[] = ['content' => $content, 'is_correct' => $index === $answer];
        }

        return [
            'type' => 'mcq',
            'content' => $q,
            'explanation' => $explanation ?: null,
            'difficulty' => $difficulty,
            'options' => $mapped,
        ];
    }

    private static function easyTrueFalse(string $q, bool $answer, string $explanation = ''): array
    {
        return self::tf('easy', $q, $answer, $explanation);
    }

    private static function hardTrueFalse(string $q, bool $answer, string $explanation = ''): array
    {
        return self::tf('hard', $q, $answer, $explanation);
    }

    private static function tf(string $difficulty, string $q, bool $answer, string $explanation): array
    {
        return [
            'type' => 'true_false',
            'content' => $q,
            'explanation' => $explanation ?: null,
            'difficulty' => $difficulty,
            'correct_answer' => $answer,
        ];
    }
