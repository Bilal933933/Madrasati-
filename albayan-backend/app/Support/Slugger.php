<?php

namespace App\Support;

use Illuminate\Support\Str;

/**
 * مولّد الروابط (Slug) — كود عام مشترك بين الدومينات.
 *
 * القاعدة:
 * - إن أدخل المدير slug إنجليزيًا بنفسه → يُستخدم كما هو.
 * - إن تُرك فارغًا → يُولَّد تلقائيًا: ترجمة الاسم العربي إلى لاتيني + "-" + id
 *   (مثل: "رياضيات" → "ryadyat-5") لضمان التفرد دائمًا.
 */
class Slugger
{
    private const ARABIC_TO_LATIN = [
        'أ' => 'a', 'إ' => 'a', 'آ' => 'a', 'ا' => 'a', 'ء' => 'a',
        'ب' => 'b', 'ت' => 't', 'ث' => 'th', 'ج' => 'j', 'ح' => 'h',
        'خ' => 'kh', 'د' => 'd', 'ذ' => 'dh', 'ر' => 'r', 'ز' => 'z',
        'س' => 's', 'ش' => 'sh', 'ص' => 's', 'ض' => 'd', 'ط' => 't',
        'ظ' => 'z', 'ع' => 'a', 'غ' => 'gh', 'ف' => 'f', 'ق' => 'q',
        'ك' => 'k', 'ل' => 'l', 'م' => 'm', 'ن' => 'n', 'ه' => 'h',
        'و' => 'w', 'ي' => 'y', 'ة' => 'h', 'ى' => 'a',
        'ئ' => 'y', 'ؤ' => 'w', 'ي' => 'y',
        'َ' => '', 'ُ' => '', 'ِ' => '', 'ً' => '', 'ٌ' => '', 'ٍ' => '',
        'ْ' => '', 'ّ' => '', 'ـ' => '',
    ];

    /**
     * توليد slug من الاسم + id.
     */
    public static function from(string $name, int $id): string
    {
        $base = Str::slug(strtr($name, self::ARABIC_TO_LATIN));

        if ($base === '') {
            $base = 'item';
        }

        return $base.'-'.$id;
    }
}
